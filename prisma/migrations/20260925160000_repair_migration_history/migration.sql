-- never given a migration. The history therefore could not produce the schema the
-- code compiles against, so a new developer, a staging instance or a
-- disaster-recovery rebuild all failed the same way. Production was fine; only
-- reproducibility was broken, which is the kind of fault that stays invisible
-- until the day it is urgent.
--
-- ── WHAT THIS ADDS ────────────────────────────────────────────────────────
--
--   3 enum types   CppRevisionStatus, ArrangementKey, RiskTopic   (CPP work)
