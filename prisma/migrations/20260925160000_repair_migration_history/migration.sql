--                  (the invite name split and CSCS scheme selection)
--   index and default alignment, so a rebuilt database matches schema.prisma
--   exactly rather than nearly.
--
-- ── IT IS NOT RUN AGAINST PRODUCTION ──────────────────────────────────────
--
-- Production already has every object above; `prisma migrate diff` from the live
-- database to schema.prisma confirmed it. This migration is recorded there as
-- applied (`prisma migrate resolve --applied`) rather than executed, because
-- executing it would drop four indexes and several DEFAULTs that production has
-- been running with and that nothing asked to change. The generated statements
-- below are written for a database built from migrations, which is the only place
-- they need to run.
--
-- Generated by `prisma migrate diff --from-migrations --to-schema-datamodel`, so
-- it is the tool's own answer rather than a hand-written guess, and verified by
-- rebuilding from scratch and re-diffing to empty.

